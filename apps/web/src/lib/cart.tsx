import {
  createContext,
  useCallback,
  useContext,
  useEffect,
  useMemo,
  useRef,
  useState,
} from "react";

const CART_KEY = "sweet-treats-lr-cart";
const CART_ID_KEY = "sweet-treats-lr-cart-id";

export type CartMenuItem = {
  id: string;
  name: string;
  priceCents: number;
  imageKey?: string | null;
  available?: boolean;
  inventoryQuantity?: number;
  trackInventory?: boolean;
  /** False for pickup-only items (cakes, shakes); blocks the Ship branch. */
  isShippable?: boolean;
  /** Number of cookies when this item is a pack/box. */
  packSize?: number | null;
};

export type CartLine = CartMenuItem & {
  quantity: number;
};

type CartContextValue = {
  lines: CartLine[];
  /** False until the saved cart has been read from localStorage on the client. */
  ready: boolean;
  count: number;
  subtotalCents: number;
  /** Stable id for this cart: order idempotency + abandoned-cart tracking. */
  clientOrderId: string;
  addItem: (item: CartMenuItem, quantity?: number) => void;
  removeItem: (id: string) => void;
  increase: (id: string) => void;
  decrease: (id: string) => void;
  clear: () => void;
};

const CartContext = createContext<CartContextValue | null>(null);

function maxQuantity(item: CartMenuItem) {
  return item.trackInventory && typeof item.inventoryQuantity === "number"
    ? Math.max(0, item.inventoryQuantity)
    : 24;
}

function readInitialCart() {
  if (typeof window === "undefined") {
    return [];
  }

  try {
    const parsed = JSON.parse(window.localStorage.getItem(CART_KEY) ?? "[]");
    return Array.isArray(parsed) ? (parsed as CartLine[]) : [];
  } catch {
    return [];
  }
}

/** Stable per-cart id; regenerated by clear() so a new cart is a new id. */
function readCartId(): string {
  if (typeof window === "undefined") {
    return "";
  }
  let id = window.localStorage.getItem(CART_ID_KEY) ?? "";
  if (!id) {
    id = crypto.randomUUID();
    window.localStorage.setItem(CART_ID_KEY, id);
  }
  return id;
}

export function CartProvider({ children }: { children: React.ReactNode }) {
  const [lines, setLines] = useState<CartLine[]>([]);
  const [hasLoaded, setLoaded] = useState(false);
  const [cartId, setCartId] = useState("");
  const [trackVersion, setTrackVersion] = useState(0);

  useEffect(() => {
    setLines(readInitialCart());
    setCartId(readCartId());
    setLoaded(true);
  }, []);

  useEffect(() => {
    if (!hasLoaded) {
      return;
    }

    window.localStorage.setItem(CART_KEY, JSON.stringify(lines));
    // Any content change restarts the tracking debounce.
    setTrackVersion((version) => version + 1);
  }, [hasLoaded, lines]);

  const clear = useCallback(() => {
    setLines([]);
    if (typeof window !== "undefined") {
      // Fresh id for the next cart.
      const nextId = crypto.randomUUID();
      window.localStorage.setItem(CART_ID_KEY, nextId);
      setCartId(nextId);
    }
  }, []);

  const addItem = useCallback((item: CartMenuItem, quantity = 1) => {
    setLines((current) => {
      const max = maxQuantity(item);
      if (max <= 0) {
        return current;
      }

      const existing = current.find((line) => line.id === item.id);
      if (existing) {
        return current.map((line) =>
          line.id === item.id
            ? { ...line, ...item, quantity: Math.min(max, line.quantity + quantity) }
            : line,
        );
      }

      return [...current, { ...item, quantity: Math.min(max, quantity) }];
    });
  }, []);

  const removeItem = useCallback((id: string) => {
    setLines((current) => current.filter((line) => line.id !== id));
  }, []);

  const increase = useCallback((id: string) => {
    setLines((current) =>
      current.map((line) =>
        line.id === id
          ? { ...line, quantity: Math.min(maxQuantity(line), line.quantity + 1) }
          : line,
      ),
    );
  }, []);

  const decrease = useCallback((id: string) => {
    setLines((current) =>
      current
        .map((line) => (line.id === id ? { ...line, quantity: line.quantity - 1 } : line))
        .filter((line) => line.quantity > 0),
    );
  }, []);

  // Debounced server ping for abandoned-cart tracking. Runs 30 seconds after
  // the cart settles — never on every keystroke.
  const trackTimer = useRef<ReturnType<typeof setTimeout> | null>(null);
  useEffect(() => {
    if (!hasLoaded || !cartId || trackVersion === 0) {
      return;
    }
    if (trackTimer.current) {
      clearTimeout(trackTimer.current);
    }
    trackTimer.current = setTimeout(() => {
      import("./api")
        .then(({ trackCart }) =>
          trackCart({
            data: {
              clientOrderId: cartId,
              items: lines.map((line) => ({ id: line.id, quantity: line.quantity })),
            },
          }),
        )
        .catch(() => {});
    }, 30_000);
    return () => {
      if (trackTimer.current) {
        clearTimeout(trackTimer.current);
      }
    };
  }, [hasLoaded, cartId, trackVersion, lines]);

  const value = useMemo(() => {
    const count = lines.reduce((sum, line) => sum + line.quantity, 0);
    const subtotalCents = lines.reduce((sum, line) => sum + line.quantity * line.priceCents, 0);

    return {
      lines,
      ready: hasLoaded,
      count,
      subtotalCents,
      clientOrderId: cartId,
      addItem,
      removeItem,
      increase,
      decrease,
      clear,
    };
  }, [addItem, cartId, clear, decrease, hasLoaded, increase, lines, removeItem]);

  return <CartContext.Provider value={value}>{children}</CartContext.Provider>;
}

export function useCart() {
  const cart = useContext(CartContext);
  if (!cart) {
    throw new Error("useCart must be used within CartProvider");
  }

  return cart;
}
